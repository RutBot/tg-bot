package ru.kruasanich.telegram.bot.engine.core.model

import ru.kruasanich.telegram.bot.engine.core.session.UserSession

/**
 * Экран сценария — атомарный узел взаимодействия с пользователем.
 *
 * Экран отвечает за две вещи:
 *  - предоставить контент и клавиатуру для отображения ([view]);
 *  - при необходимости обработать свободный текстовый ввод ([onText]).
 *
 * Интерфейс намеренно узкий: вся бизнес-логика конкретного бота описывается
 * данными ([ScreenView]) и переходами, а не наследованием.
 */
interface Screen {

    /** Уникальный идентификатор экрана в рамках сценария. */
    val id: ScreenId

    /**
     * Построить отображение экрана для конкретной сессии.
     *
     * Метод асинхронный: контент может зависеть от данных пользователя,
     * подгружаемых из внешних источников.
     *
     * @param session текущая сессия пользователя.
     * @return контент и клавиатура для показа.
     */
    suspend fun view(session: UserSession): ScreenView

    /**
     * Обработать свободный текстовый ввод пользователя на этом экране.
     *
     * Возвращает `null`, если экран не ожидает текстового ввода
     * (тогда движок проигнорирует ввод или покажет подсказку).
     *
     * @param session текущая сессия пользователя.
     * @param text введённый пользователем текст.
     * @return результат обработки ввода или `null`, если ввод не поддерживается.
     */
    suspend fun onText(session: UserSession, text: String): InputResult? = null

    /**
     * Проверить право входа на экран (declarative guard).
     *
     * Вызывается движком перед переходом на экран. Возвращает `null`, если вход
     * разрешён, либо [ScreenId] экрана-перенаправления (например, «занятие
     * закрыто»), если доступ запрещён. Это поднимает gating/контроль доступа
     * в декларативный слой — как фильтр/интерсептор маршрута, — вместо `if`-ов,
     * разбросанных по обработчикам действий.
     *
     * @param session текущая сессия пользователя.
     * @return `null` если разрешено, иначе экран-перенаправление.
     */
    suspend fun guard(session: UserSession): ScreenId? = null

    /**
     * Хук входа на экран (вызывается при переходе вперёд и на `/start`).
     *
     * Удобен для инициализации состояния экрана — например, сброса индекса
     * пошагового экрана или формы при каждом новом входе. Не вызывается при
     * перерисовке текущего экрана и при возврате «назад».
     *
     * @param session текущая сессия пользователя.
     */
    suspend fun onEnter(session: UserSession) {}
}

/**
 * Готовое к отображению представление экрана.
 *
 * @property content контент экрана.
 * @property buttons клавиатура (строки кнопок); пустой список — без клавиатуры.
 */
data class ScreenView(
    val content: ScreenContent,
    val buttons: List<List<Button>> = emptyList(),
)

/**
 * Результат обработки текстового ввода экраном.
 *
 * @property reply опциональный текстовый ответ пользователю.
 * @property next экран, на который нужно перейти после обработки;
 *  `null` — остаться на текущем экране.
 */
data class InputResult(
    val reply: String? = null,
    val next: ScreenId? = null,
)
